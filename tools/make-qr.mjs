#!/usr/bin/env node
// Writes assets/qr.svg: a scalable QR code for the game URL.
//
// Usage:
//   node tools/make-qr.mjs [url]
//
// Default URL: https://bagmk.github.io/before-he-stood/
//
// Needs the `qrcode` npm package (1.5.x). It is not a project dependency, so
// install it somewhere outside the repo first, for example:
//   npm i --prefix /tmp/qr qrcode@1.5.4
// The script looks for it in $QRCODE_DIR, then /tmp/qr, then the repo itself.
//
// Output: dark modules on a white background, a 4-module quiet zone,
// error correction level M, viewBox-based so it scales to any size.

import { createRequire } from "node:module";
import { mkdirSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const DEFAULT_URL = "https://bagmk.github.io/before-he-stood/";

const here = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(here, "..");
const outFile = join(repoRoot, "assets", "qr.svg");

function loadQrcode() {
  const candidates = [process.env.QRCODE_DIR, "/tmp/qr", repoRoot].filter(Boolean);
  for (const dir of candidates) {
    if (!existsSync(join(dir, "node_modules", "qrcode"))) continue;
    try {
      // createRequire resolves "qrcode" from that directory's node_modules.
      return createRequire(join(dir, "package.json"))("qrcode");
    } catch (err) {
      // Try the next candidate.
    }
  }
  console.error(
    "Could not find the `qrcode` package.\n" +
      "Install it outside the repo, then run this script again:\n" +
      "  npm i --prefix /tmp/qr qrcode@1.5.4\n" +
      "Or point QRCODE_DIR at a folder whose node_modules contains qrcode."
  );
  process.exit(1);
}

function escapeXml(s) {
  return String(s)
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");
}

async function main() {
  const url = (process.argv[2] || DEFAULT_URL).trim();
  if (!/^https?:\/\//i.test(url)) {
    console.error("Expected an http(s) URL, got: " + url);
    process.exit(1);
  }

  const QRCode = loadQrcode();
  let svg = await QRCode.toString(url, {
    type: "svg",
    errorCorrectionLevel: "M",
    margin: 4,
    width: 480,
    color: { dark: "#000000", light: "#ffffff" }
  });

  // Add an accessible title and keep the encoded URL visible in the source.
  svg = svg
    .trim()
    .replace(
      /^<svg /,
      '<svg role="img" aria-label="' + escapeXml("QR: " + url) + '" '
    )
    .replace(/(<svg[^>]*>)/, "$1<title>" + escapeXml(url) + "</title>");

  const header = "<!-- QR code for " + escapeXml(url) + " (generated by tools/make-qr.mjs) -->\n";
  mkdirSync(dirname(outFile), { recursive: true });
  writeFileSync(outFile, header + svg + "\n", "utf8");

  const modules = QRCode.create(url, { errorCorrectionLevel: "M" }).modules.size;
  console.log("Wrote " + outFile);
  console.log("URL: " + url);
  console.log("Modules: " + modules + "x" + modules + " plus a 4-module quiet zone");
}

main().catch((err) => {
  console.error(err && err.stack ? err.stack : err);
  process.exit(1);
});
